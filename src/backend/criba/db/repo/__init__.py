"""Repository layer: Candidates, Applications and their lifecycle, messages, events,
Claims, Reopen, the review queue, the scheduler's Stalled ladder and flags, and the
Application JSON export. SQL lives here (``tests/db/test_no_sql_outside_db.py``).

Vocabulary follows CONTEXT.md; rules follow ADRs 0016, 0020, 0021, 0033 and the Phase 1
detailed spec. Every function takes an open connection (see ``criba.db.connect``)
and an optional ``now`` (timezone-aware ``datetime``) so callers can drive time
from a ``Clock``. Multi-row writes run inside :func:`transaction`, which nests, so
callers may group several calls into one atomic unit.

Application dicts returned here decode the JSON columns (``availability``,
``preferred_schedule``, ``experience_platforms``, ``summary_structured``) to Python
lists and dicts, and the 0/1 columns to ``bool``.

The code lives in one module per aggregate, layered so imports only go one way:
``base``, ``events``, ``handbacks``, ``applications`` (reading), ``candidates``,
``queue``, ``lifecycle`` (start, resolve, Reopen), ``outcomes`` (stages, answers,
Outcomes), ``messages``, ``claims``, ``export``, plus eight leaves that import no sibling:
``scheduling`` (the Stalled ladder and flags), ``zones``, ``bookings`` (slots, offers and
bookings), ``held_actions`` (quiet-hours deferral), ``voice_sessions`` (voice calls),
``slots`` (interview slot management), ``owed_turns`` (the turn recovery, ADR 0073) and
``metrics`` (results and usage-ledger reads).
Callers use this package as one module (``from criba.db import repo``; ``repo.<name>``).
A test that monkeypatches ``repo.<name>`` patches this facade only: a function inside the
package that calls a sibling by name (``mark_qualified`` and ``hold_for_recruiters`` call
``open_queue_item``) does not see the patch.
"""

